/** Only expose known business errors, never raw database details. */
export function confirmError(error: { code?: string; message?: string }) {
  if (error.code === '23505') return '這個賣貨便編號已被其他轉單使用，請核對編號；本批保留待核對。'
  const messages: Record<string, string> = {
    '原訂單狀態已改變，請人工核對': '原訂單已變更狀態。若已人工出貨，需先套用「已出貨補記編號」資料庫修正；不需重新下單。',
    '原訂單狀態不允許回填': '原訂單目前不是待確認或已出貨，請先確認是否已取消或進入其他流程。',
    '原訂單內容已改變，請人工核對': '收件資料、商品或其他訂單內容與匯出時不同，尚未回填。請核對賣貨便實際訂單；可保留此批並繼續其他訂單。',
    '此訂單已記錄其他賣貨便編號': '這筆訂單已有不同的賣貨便編號，請到批次紀錄查看，不能直接覆蓋。',
    '轉單紀錄不存在': '找不到這筆轉單紀錄，請重新整理批次紀錄。',
    '原訂單不存在': '原訂單已不存在，保留批次供人工核對。',
    '此批次已解除保留': '這筆已解除保留，不能回填到舊紀錄，請核對目前的批次。',
  }
  return messages[error.message || ''] || '回寫暫時失敗，批次仍保留。請稍後讀回結果，不要重新匯入同一批。'
}
