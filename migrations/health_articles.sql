## 我才知道，失智症不是「老化的必然」

我認真去研究、去問醫生，發現幾個重要的事實：

**1. 失智症不是正常老化**

正常老化會偶爾忘東西，但會記起來、不影響生活。**失智症是真的記不起來**，會影響日常運作。

**2. 失智症是病**

媽媽不是「年紀大就這樣」，是大腦真的有病變。

**3. 40% 失智症可以預防**

世界頂級醫學期刊研究，**透過生活方式可以預防 40% 的失智症**。這給我很大的希望。

**4. 越早保養越好**

失智症不是 70 歲才開始的，**大腦病變可能 20 年前就開始了**。50 歲開始保養剛好。

## 你或家人有這些徵兆嗎

如果有以下狀況，請特別注意：

- **重複問同樣問題**（最重要警訊）
- 忘記剛剛發生的事
- 對熟悉的事失去判斷力（迷路、財務出錯）
- 個性突然改變
- 學新東西變得很困難
- 找不到適當的詞彙
- 把東西放在奇怪的地方（冰箱裡找到鑰匙）
- 對日常活動失去興趣

如果家人有這些，**早期診斷很重要，可以延緩病程**。

## 我這 5 年做的事

媽媽診斷出來後，我認真改變生活：

**1. 重訓 + 有氧運動**

這是研究中最有效的單一行為。**運動會促進腦源神經滋養因子 BDNF**，幫助腦細胞健康。我每週 3 次重訓 + 4 次健走。

**2. 學新東西**

我開始學日文（55 歲開始），手忙腳亂但很有趣。**學新東西是最強健腦活動**，不是填字遊戲那種重複動腦。

**3. 把社交活動排進每週**

孤獨是失智症大風險。我固定跟同學聚會、參加讀書會。**社交對大腦比想像中重要**。

**4. 飲食大調整**

地中海飲食、MIND 飲食、得舒飲食，這幾種研究都證實對大腦好。我的版本是：
- 多深綠葉菜
- 多莓果
- 多堅果
- 多魚類
- 橄欖油為主
- 少紅肉、少糕點

**5. 控制三高**

高血壓、糖尿病都會傷害大腦血管。我認真控血壓血糖。

**6. 睡眠**

睡眠時大腦會清理累積的「廢物蛋白質」（就是失智症元兇之一）。**睡不好等於不清理大腦**。

**7. 戴助聽器（因為媽媽聽力不好沒戴）**

研究發現**聽力受損會增加失智症風險**。如果聽不清，不要忍，去配。

**8. 戒菸限酒**

兩個都會傷大腦。

