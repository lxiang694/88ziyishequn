- 油炸、加工肉品
- 反式脂肪（瑪琪琳、酥油）

## 我發現有用的「小撇步」

**先吃菜、再吃肉、最後吃飯**

血糖比較不會飆，飽足感也好。

**用小一點的盤子**

聽起來無聊但真的有用，視覺感影響食量。

**慢慢吃，每口嚼 20 下**

大腦感受飽足要 20 分鐘。狼吞虎嚥很容易吃過量。

**不要挨餓減肥**

挨餓會降低基礎代謝，**之後吃一點點就胖**。我犯過這個錯。

**體重 vs 腰圍**

別只看體重。**腰圍下降比體重下降更有意義**（代表內臟脂肪減少）。

## 保健品我有試過的

說實話**保健品只是輔助**，沒有產品能取代飲食和運動。但有些我用過覺得不錯：

**乳清蛋白**：飯後或運動後喝，幫助增肌

**左旋肉鹼**：搭配運動感覺脂肪燃燒比較好

**綠茶兒茶素**：天然燃脂，但效果輕微

**白腎豆**：吃澱粉前吃，幫助阻斷部分吸收

**鉻**：穩定血糖，減少甜食慾望

**B 群**：能量代謝

**益生菌**：腸道菌相和體重有關

**Omega-3**：抗發炎

## 一定要看醫生的狀況

- 不明原因體重快速增加（甲狀腺、藥物副作用？）
- 不明原因體重快速減輕（要排除糖尿病、癌症）
- 努力控制飲食運動仍無效（內分泌問題？）
- 暴食或催吐（飲食障礙）

## 三個重要觀念

**觀念一**：「不吃飯減最快」

**錯**。完全不碳水會降低基礎代謝、影響大腦、容易暴食復胖。**選對碳水**比不吃更重要。

**觀念二**：「只做有氧減肥就好」

**錯**。純有氧會同時減掉肌肉，越減代謝越慢。**重訓 + 有氧**才能塑造健康體態。

**觀念三**：「保健品可以幫我輕鬆瘦」

**錯**。保健品只是輔助，**真正關鍵是飲食、運動、睡眠**。沒有任何產品能取代這些。

