## 動腦活動的選擇

我發現**單一動腦不夠，要組合**：

**動腦 + 動身體**

跳舞、太極、瑜珈是最好的。同時刺激很多腦區。

**社交 + 動腦**

打麻將、橋牌、讀書會。**有人互動的動腦比一個人解填字遊戲好**。

**學新技能**

學樂器、學語言、學書法、學烹飪新菜。**真的學新東西，不是重複熟悉的活動**。

**閱讀**

讀有挑戰性的書（不是滑短影片）。

