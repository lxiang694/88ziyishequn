--    這個名稱只顯示在後台的「處理賣場」下拉選單，讓你分辨是哪一個，
--    不會出現在客戶看得到的任何地方，所以取你自己認得的就好。
--
-- ⚠️ temperature 預設常溫。這個賣場如果是冷凍商品，改成 '冷凍' ——
--    它會寫進匯入檔的溫層欄位，填錯會被賣貨便退件。

INSERT INTO myship_marketplaces (id, name, temperature, enabled)
VALUES ('GM2604107313905', '請填入賣場名稱', '常溫', true)
ON CONFLICT (id) DO UPDATE
  SET name = EXCLUDED.name,
      temperature = EXCLUDED.temperature,
      enabled = EXCLUDED.enabled;

-- 確認結果
SELECT id, name, temperature, enabled FROM myship_marketplaces ORDER BY id;

