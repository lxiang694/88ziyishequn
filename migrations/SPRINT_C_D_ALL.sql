-- ── 7. 接受邀請：資料庫端的並發保護 ───────────────────────
-- 兩位兼職同時按下「接受」時，靠這支函式的 row lock 保證最多一個成功。
-- 不能只靠前端 disabled 按鈕，也不能靠應用層先讀後寫。
create or replace function care_accept_dispatch_proposal(
  p_proposal_id bigint, p_companion_id bigint
) returns table (ok boolean, reason text, out_booking_id bigint)
language plpgsql as $$
declare
  v_p care_dispatch_proposals%rowtype;
  v_assigned bigint;
  v_emp text;
begin
  select * into v_p from care_dispatch_proposals where id = p_proposal_id for update;
  if not found then
    return query select false, 'proposal_not_found', null::bigint; return;
  end if;
  if v_p.companion_id <> p_companion_id then
    return query select false, 'not_your_proposal', null::bigint; return;
  end if;
  if v_p.status <> 'proposed' then
    return query select false, 'proposal_not_open', null::bigint; return;
  end if;
  if v_p.expires_at <= now() then
    update care_dispatch_proposals set status = 'expired', updated_at = now()
      where id = p_proposal_id;
    return query select false, 'proposal_expired', null::bigint; return;
  end if;

  -- 僱用條件必須仍然有效
  select employment_type into v_emp from staff_employment_terms
    where companion_id = p_companion_id and status = 'active'
      and effective_from <= current_date
      and (effective_to is null or effective_to >= current_date)
    limit 1;
  if v_emp is null then
    return query select false, 'employment_inactive', null::bigint; return;
  end if;

  -- 鎖住服務列，確認還沒有人被指派
  select companion_id into v_assigned from care_bookings
    where id = v_p.booking_id for update;
  if v_assigned is not null then
    update care_dispatch_proposals set status = 'cancelled', updated_at = now()
      where id = p_proposal_id;
    return query select false, 'already_assigned', null::bigint; return;
  end if;

  -- 正式指派：設定 companion_id 就是既有的 Assignment 語意
  update care_bookings
    set companion_id = p_companion_id, status = '已派工', updated_at = now()
    where id = v_p.booking_id;

  update care_dispatch_proposals
    set status = 'accepted', responded_at = now(), updated_at = now()
    where id = p_proposal_id;

  -- 同一筆服務的其他未回覆邀請一併撤回，讀取範圍立即收回
  update care_dispatch_proposals
    set status = 'cancelled', updated_at = now()
    where booking_id = v_p.booking_id and id <> p_proposal_id and status = 'proposed';

  return query select true, 'ok', v_p.booking_id;
end $$;

-- ── 8. 狀態機守衛 ──────────────────────────────────────────
create or replace function care_guard_proposal() returns trigger
language plpgsql as $$
begin
  if new.status is distinct from old.status then
    if not (
      (old.status = 'proposed' and new.status in ('accepted','declined','expired','cancelled'))
    ) then
      raise exception 'care_dispatch_proposal: 不允許的狀態轉換 % -> %', old.status, new.status
        using errcode = 'check_violation';
    end if;
  end if;
  return new;
end $$;
drop trigger if exists trg_cdp_guard on care_dispatch_proposals;
create trigger trg_cdp_guard before update on care_dispatch_proposals
  for each row execute function care_guard_proposal();

