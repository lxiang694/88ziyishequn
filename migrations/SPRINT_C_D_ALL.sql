create or replace function care_guard_settlement_line() returns trigger
language plpgsql as $$
begin
  -- 全職不在本輪產生報酬 line
  if new.employment_type_snapshot = 'fulltime' then
    raise exception '全職陪診員本輪不產生結算 line，只提供服務統計'
      using errcode = 'check_violation';
  end if;

  if TG_OP = 'UPDATE' then
    -- 已發布給陪診員或已入批次的金額不可再改
    if old.status in ('published_to_staff','batched')
       and (new.amount is distinct from old.amount
            or new.line_type is distinct from old.line_type
            or new.basis_snapshot is distinct from old.basis_snapshot) then
      raise exception '已發布或已入批次的結算明細不可修改金額'
        using errcode = 'check_violation';
    end if;

    if new.status is distinct from old.status then
      if not (
        (old.status = 'pending_review'     and new.status in ('approved','rejected')) or
        (old.status = 'approved'           and new.status in ('batched','published_to_staff','pending_review')) or
        (old.status = 'batched'            and new.status in ('published_to_staff')) or
        (old.status = 'rejected'           and new.status in ('pending_review'))
      ) then
        raise exception 'care_settlement_line: 不允許的狀態轉換 % -> %', old.status, new.status
          using errcode = 'check_violation';
      end if;
    end if;
  end if;
  return new;
end $$;

