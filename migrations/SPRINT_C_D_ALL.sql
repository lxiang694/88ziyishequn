-- 一筆服務同時只能有一份「進行中」的紀錄
create unique index if not exists uniq_care_rec_active_per_booking
  on care_service_records(booking_id)
  where status in ('draft','submitted','returned_for_revision');

create or replace function care_guard_service_record() returns trigger
language plpgsql as $$
begin
  -- 已核可的紀錄內容不可被無聲改寫
  if old.status = 'reviewed' then
    if new.objective_summary is distinct from old.objective_summary
       or new.met_completed is distinct from old.met_completed
       or new.checkin_completed is distinct from old.checkin_completed
       or new.process_handover_completed is distinct from old.process_handover_completed
       or new.return_arrangement_completed is distinct from old.return_arrangement_completed
       or new.family_contact_completed is distinct from old.family_contact_completed
       or new.family_follow_up_needed is distinct from old.family_follow_up_needed then
      raise exception '已核可的服務紀錄不可修改內容，請建立新版本'
        using errcode = 'check_violation';
    end if;
  end if;

  -- 送審後陪診員不可再改內容（只有督導退回才能重新編輯）
  if old.status = 'submitted' and new.status = 'submitted' then
    if new.objective_summary is distinct from old.objective_summary then
      raise exception '已送審的服務紀錄不可修改，請先由督導退回'
        using errcode = 'check_violation';
    end if;
  end if;

  if new.status is distinct from old.status then
    if not (
      (old.status = 'draft'                 and new.status in ('submitted','superseded')) or
      (old.status = 'submitted'             and new.status in ('reviewed','returned_for_revision')) or
      (old.status = 'returned_for_revision' and new.status in ('submitted','superseded')) or
      (old.status = 'reviewed'              and new.status in ('superseded'))
    ) then
      raise exception 'care_service_record: 不允許的狀態轉換 % -> %', old.status, new.status
        using errcode = 'check_violation';
    end if;
  end if;
  return new;
end $$;

drop trigger if exists trg_care_rec_guard on care_service_records;
create trigger trg_care_rec_guard before update on care_service_records
  for each row execute function care_guard_service_record();

