-- ── 10. Backfill：從既有欄位補資料 ────────────────────────
-- 僱用型態：從 companions.employment_type 帶入。
-- 舊值只有 fulltime / parttime 兩種，對應明確，不是猜測。
-- 若日後出現無法對應的值，會留在 needs_review 由人工補。
insert into staff_employment_terms (companion_id, employment_type, status, effective_from, note)
select c.id,
       case c.employment_type when 'fulltime' then 'full_time' else 'part_time' end,
       case when c.status = 'suspended' then 'paused' else 'active' end,
       coalesce(c.created_at::date, current_date),
       '由 companions.employment_type 自動帶入（Sprint C backfill）'
from companions c
where c.employment_type in ('fulltime', 'parttime')
  and not exists (select 1 from staff_employment_terms t where t.companion_id = c.id);

