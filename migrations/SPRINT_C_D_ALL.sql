-- ── 1. 受控服務事件 ────────────────────────────────────────
create table if not exists care_service_events (
  id              bigint generated by default as identity primary key,
  booking_id      bigint not null references care_bookings(id) on delete restrict,
  companion_id    bigint references companions(id),

  event_type      text not null,
  -- 對家屬可見的簡短訊息，非醫療內容，長度受限
  family_note     text,
  -- internal：只有後台看得到；family：已允許對家屬顯示
  visibility      text not null default 'internal',

  -- 更正留痕：不刪除事件，改以 invalidated 標記並指向更正事件
  invalidated_at        timestamptz,
  invalidated_by_type   text,
  invalidate_reason_code text,
  supersedes_event_id   bigint references care_service_events(id),

  -- 事件時間一律由資料庫寫入，client 不得指定
  occurred_at     timestamptz not null default now(),
  created_at      timestamptz not null default now(),

  constraint care_evt_type_chk check (event_type in (
    'staff_arrived','beneficiary_met','registration_or_checkin_completed',
    'waiting_or_process_in_progress','process_transition',
    'return_arrangement_confirmed','service_handover_ready',
    'requires_supervisor_attention')),
  constraint care_evt_visibility_chk check (visibility in ('internal','family')),
  constraint care_evt_note_len_chk check (family_note is null or char_length(family_note) <= 120),
  constraint care_evt_invalidate_reason_chk check (
    invalidated_at is null or invalidate_reason_code is not null)
);
create index if not exists idx_care_evt_booking on care_service_events(booking_id, occurred_at desc);
create index if not exists idx_care_evt_companion on care_service_events(companion_id);
create index if not exists idx_care_evt_type on care_service_events(event_type);

-- append-only：已建立的事件不可刪除，也不可改寫內容
create or replace function care_guard_service_event() returns trigger
language plpgsql as $$
begin
  if TG_OP = 'DELETE' then
    raise exception 'care_service_events 為 append-only，不可刪除'
      using errcode = 'check_violation';
  end if;
  -- 只允許標記作廢，其餘欄位一律凍結
  if new.booking_id     is distinct from old.booking_id
     or new.companion_id is distinct from old.companion_id
     or new.event_type   is distinct from old.event_type
     or new.family_note  is distinct from old.family_note
     or new.occurred_at  is distinct from old.occurred_at
     or new.created_at   is distinct from old.created_at then
    raise exception 'care_service_events 為 append-only，只能標記作廢，不可改寫內容'
      using errcode = 'check_violation';
  end if;
  if old.invalidated_at is not null and new.invalidated_at is distinct from old.invalidated_at then
    raise exception '事件已作廢，不可重複作廢' using errcode = 'check_violation';
  end if;
  return new;
end $$;

drop trigger if exists trg_care_evt_guard on care_service_events;
create trigger trg_care_evt_guard before update or delete on care_service_events
  for each row execute function care_guard_service_event();

