-- ── 3. 服務過程記錄（時間軸）────────────────────────────────
create table if not exists care_booking_events (
  id           bigint generated by default as identity primary key,
  booking_id   bigint not null references care_bookings(id) on delete cascade,
  companion_id bigint references companions(id),
  event_type   text not null,
  -- accepted 接受派工 / declined 婉拒 / contacted 行前電話確認 /
  -- met 已會合 / progress 服務進度 / doctor_note 醫師重要提醒 / completed 服務完成
  note         text,
  photos       jsonb default '[]'::jsonb,   -- storage 路徑陣列（私有）
  created_at   timestamptz default now()
);
create index if not exists idx_care_events_booking on care_booking_events(booking_id);
create index if not exists idx_care_events_created on care_booking_events(created_at);

