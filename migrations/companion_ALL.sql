-- ── 2. 陪診員 ──────────────────────────────────────────────
create table if not exists companions (
  id              bigint generated by default as identity primary key,
  name            text not null,
  phone           text not null unique,          -- 同時作為登入帳號
  email           text,
  password_hash   text not null,
  gender          text,                          -- female / male / na（部分長輩偏好同性陪診）
  employment_type text default 'parttime',       -- fulltime / parttime
  service_areas   jsonb default '[]'::jsonb,     -- 可服務縣市
  certifications  text,                          -- 證照：照服員、CPR、BLS…
  bio             text,
  status          text default 'pending',        -- pending 待審核 / active 啟用 / suspended 停用
  completed_count integer default 0,
  admin_note      text,
  created_at      timestamptz default now()
);
create index if not exists idx_companions_status on companions(status);

-- ── 3. 陪診員可服務時段 ────────────────────────────────────
create table if not exists companion_availability (
  id           bigint generated by default as identity primary key,
  companion_id bigint not null references companions(id) on delete cascade,
  date         date not null,
  time_slot    text not null,                    -- morning / afternoon / allday
  created_at   timestamptz default now(),
  unique (companion_id, date, time_slot)
);
create index if not exists idx_avail_date on companion_availability(date);

-- ── 4. 陪診預約 ────────────────────────────────────────────
create table if not exists care_bookings (
  id             bigint generated by default as identity primary key,
  booking_no     text unique not null,
  -- 方案（下單當下快照，日後改價不影響既有預約）
  service_code   text,
  service_name   text,
  price          integer,
  -- 就診人
  patient_name   text not null,
  patient_age    text,
  patient_gender text,
  mobility       text,          -- walk 自行行走 / assist 需攙扶 / wheelchair 輪椅
  -- 聯絡人（多半是子女）
  contact_name   text not null,
  contact_phone  text not null,
  contact_line   text,
  relation       text,          -- 與就診人關係
  -- 就醫資訊
  service_date   date not null,
  time_slot      text,          -- morning / afternoon / allday
  county         text,
  hospital       text,
  department     text,
  addons         jsonb default '[]'::jsonb,   -- 加購：到府接送、代排隊等
  notes          text,
  -- 流程狀態
  status         text default '待確認',
  -- 待確認 → 待匯款 → 已付款 → 已派工 → 服務中 → 已完成 ／ 已取消
  companion_id   bigint references companions(id),
  admin_note     text,
  user_id        uuid,          -- 若為登入會員預約
  created_at     timestamptz default now(),
  updated_at     timestamptz default now()
);
create index if not exists idx_care_bookings_status on care_bookings(status);
create index if not exists idx_care_bookings_date on care_bookings(service_date);
create index if not exists idx_care_bookings_companion on care_bookings(companion_id);

