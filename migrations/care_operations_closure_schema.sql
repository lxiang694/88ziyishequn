-- 接受紀錄是既成事實，不可修改也不可刪除
create or replace function care_guard_policy_acceptance() returns trigger
language plpgsql as $$
begin
  if tg_op = 'INSERT' then
    new.accepted_at := now();
    return new;
  end if;
  raise exception '政策接受紀錄不可修改';
end $$;
drop trigger if exists trg_care_policy_acc_guard on care_policy_acceptances;
create trigger trg_care_policy_acc_guard before insert or update on care_policy_acceptances
  for each row execute function care_guard_policy_acceptance();
drop trigger if exists trg_care_policy_acc_nodelete on care_policy_acceptances;
create trigger trg_care_policy_acc_nodelete before delete on care_policy_acceptances
  for each row execute function care_block_delete();


