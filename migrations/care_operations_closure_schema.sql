create table if not exists care_notification_outbox (
  id            bigint generated by default as identity primary key,
  notification_id bigint not null references care_notifications(id) on delete cascade,
  channel       text not null default 'in_app',
  status        text not null default 'not_configured',
  suppression_reason_code text,

  created_at    timestamptz not null default now(),
  updated_at    timestamptz not null default now(),
  suppressed_at timestamptz,
  suppressed_by_admin_id bigint,

  constraint care_outbox_channel_chk check (channel in
    ('in_app','external_pending_configuration')),
  -- 刻意沒有 sent / delivered：沒有 provider 就不會有那些狀態
  constraint care_outbox_status_chk check (status in
    ('not_configured','queued_for_approved_provider','suppressed','cancelled')),
  constraint care_outbox_uniq unique (notification_id, channel)
);
create index if not exists idx_care_outbox_status on care_notification_outbox(status, created_at desc);


-- ── 4. 資料庫層擋下「假裝已送出」 ─────────────────────────
create or replace function care_guard_outbox() returns trigger
language plpgsql as $$
begin
  -- 這裡刻意用文字比對而不是只靠 check constraint：
  -- 就算日後有人放寬 constraint，這個 trigger 仍會擋下來。
  if new.status in ('sent','delivered','sent_or_confirmed','success') then
    raise exception '沒有已核准的外部通知 provider，不可標記為已送出';
  end if;
  if new.channel = 'external_pending_configuration'
     and new.status = 'queued_for_approved_provider' then
    raise exception '外部通知通道尚未設定，不可排入待送佇列';
  end if;
  return new;
end $$;
drop trigger if exists trg_care_outbox_guard on care_notification_outbox;
create trigger trg_care_outbox_guard before insert or update on care_notification_outbox
  for each row execute function care_guard_outbox();

-- 通知本身：已讀時間由資料庫寫，不由 client 指定
create or replace function care_guard_notification() returns trigger
language plpgsql as $$
begin
  if tg_op = 'INSERT' then
    new.created_at := now();
    new.read_at := null;
    new.archived_at := null;
    return new;
  end if;
  -- 內容一旦建立就不可改寫：通知不是可以事後編輯的訊息
  if new.title is distinct from old.title
     or new.body is distinct from old.body
     or new.link_path is distinct from old.link_path
     or new.recipient_user_id is distinct from old.recipient_user_id
     or new.recipient_companion_id is distinct from old.recipient_companion_id then
    raise exception '通知內容與收件人不可修改';
  end if;
  if new.status = 'read' and old.status = 'unread' then new.read_at := now(); end if;
  if new.status = 'archived' and old.status <> 'archived' then new.archived_at := now(); end if;
  return new;
end $$;
drop trigger if exists trg_care_notification_guard on care_notifications;
create trigger trg_care_notification_guard before insert or update on care_notifications
  for each row execute function care_guard_notification();

-- 通知不可刪除：刪掉就查不出誰在什麼時候被通知過什麼
create or replace function care_block_delete() returns trigger
language plpgsql as $$
begin
  raise exception '這張表不允許刪除，請改用狀態變更保留軌跡';
end $$;
drop trigger if exists trg_care_notification_nodelete on care_notifications;
create trigger trg_care_notification_nodelete before delete on care_notifications
  for each row execute function care_block_delete();


