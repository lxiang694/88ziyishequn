-- ── 1. 站內通知：使用者收件匣 ──────────────────────────────
-- 不是服務紀錄、不是聊天、不是外部發送紀錄。
-- title/body 只放最低必要訊息；深層頁面必須再做一次授權檢查。
create table if not exists care_notifications (
  id            bigint generated by default as identity primary key,
  -- 收件人：Supabase Auth 會員（家屬）或陪診員，兩者擇一
  recipient_user_id   uuid,
  recipient_companion_id bigint references companions(id) on delete cascade,

  booking_id    bigint references care_bookings(id) on delete restrict,
  notification_type text not null,
  status        text not null default 'unread',

  -- 最小內容：不得放病況、診斷、姓名全名、電話、地址、金額、內部備註
  title         text not null,
  body          text,
  -- 深層連結只存路徑，不存 token、不存簽名網址
  link_path     text,

  created_by_admin_id bigint,
  source_reference text,

  created_at    timestamptz not null default now(),
  read_at       timestamptz,
  archived_at   timestamptz,
  updated_at    timestamptz not null default now(),

  constraint care_notif_status_chk check (status in ('unread','read','archived')),
  constraint care_notif_type_chk check (notification_type in (
    'service_event_published','family_summary_published','family_action_needed',
    'incident_contact_requested','feedback_requested','quality_follow_up_requested',
    'staff_schedule_updated','staff_time_off_reviewed','settlement_published')),
  -- 一定要有收件人，而且只能是其中一種身分
  constraint care_notif_recipient_chk check (
    (recipient_user_id is not null and recipient_companion_id is null) or
    (recipient_user_id is null and recipient_companion_id is not null)),
  -- 內容長度上限：擋下有人把服務紀錄整段塞進來
  constraint care_notif_title_len_chk check (char_length(title) <= 60),
  constraint care_notif_body_len_chk check (body is null or char_length(body) <= 200),
  constraint care_notif_link_chk check (link_path is null or link_path like '/%')
);
create index if not exists idx_care_notif_user
  on care_notifications(recipient_user_id, status, created_at desc)
  where recipient_user_id is not null;
create index if not exists idx_care_notif_companion
  on care_notifications(recipient_companion_id, status, created_at desc)
  where recipient_companion_id is not null;
create index if not exists idx_care_notif_booking on care_notifications(booking_id);


