  status        text not null default 'submitted',
  reviewed_by_admin_id bigint,
  reviewed_at   timestamptz,

  created_at    timestamptz not null default now(),
  updated_at    timestamptz not null default now(),

  constraint care_fb_status_chk check (status in ('submitted','under_review','closed')),
  constraint care_fb_score1_chk check (score_reassurance between 1 and 5),
  constraint care_fb_score2_chk check (score_communication between 1 and 5),
  constraint care_fb_score3_chk check (score_process_support between 1 and 5),
  constraint care_fb_comment_len_chk check (comment is null or char_length(comment) <= 300),
  -- 一張邀請只收一份回饋：重試與並發都不會產生第二筆
