-- ── 10. 狀態機 trigger ─────────────────────────────────────
create or replace function care_guard_feedback() returns trigger
language plpgsql as $$
begin
  if tg_op = 'INSERT' then
    new.created_at := now();
    return new;
  end if;
  -- 分數與意見送出後不可改：改了就不是家屬當時說的話
  if new.score_reassurance is distinct from old.score_reassurance
     or new.score_communication is distinct from old.score_communication
     or new.score_process_support is distinct from old.score_process_support
     or new.comment is distinct from old.comment then
    raise exception '已送出的回饋內容不可修改';
  end if;
  if old.status = 'closed' and new.status <> 'closed' then
    raise exception '已結案的回饋不可重新開啟';
  end if;
  return new;
end $$;
drop trigger if exists trg_care_feedback_guard on care_feedback;
create trigger trg_care_feedback_guard before insert or update on care_feedback
  for each row execute function care_guard_feedback();

create or replace function care_guard_concern() returns trigger
language plpgsql as $$
begin
  if tg_op = 'INSERT' then
    if new.status <> 'open' then
      raise exception '意見案件一律從 open 開始';
    end if;
    return new;
  end if;
  if old.status in ('closed') and new.status <> 'closed' then
    raise exception '已結案的意見案件不可重新開啟';
  end if;
  if new.status = 'acknowledged' and old.status <> 'open' then
    raise exception '只有 open 可以受理';
  end if;
  if new.status = 'acknowledged' then new.acknowledged_at := coalesce(old.acknowledged_at, now()); end if;
  if new.status = 'resolved' then
    if old.status not in ('acknowledged','in_follow_up') then
      raise exception '要先受理才能標記為已處理';
    end if;
    new.resolved_at := coalesce(old.resolved_at, now());
  end if;
  if new.status = 'closed' then
    if old.status <> 'resolved' then
      raise exception '要先標記為已處理才能結案';
    end if;
    new.closed_at := coalesce(old.closed_at, now());
  end if;
  return new;
end $$;
drop trigger if exists trg_care_concern_guard on care_concerns;
create trigger trg_care_concern_guard before insert or update on care_concerns
  for each row execute function care_guard_concern();

create or replace function care_guard_quality_review() returns trigger
language plpgsql as $$
begin
  if tg_op = 'INSERT' then return new; end if;
  if old.status = 'completed' and new.status <> 'completed' then
    raise exception '已完成的品質覆核不可退回，請另建改善任務';
  end if;
  if new.status in ('completed','follow_up_required') then
    new.completed_at := coalesce(old.completed_at, now());
  end if;
  return new;
end $$;
drop trigger if exists trg_care_qr_guard on care_quality_reviews;
create trigger trg_care_qr_guard before insert or update on care_quality_reviews
  for each row execute function care_guard_quality_review();

create or replace function care_guard_policy_version() returns trigger
language plpgsql as $$
begin
  if tg_op = 'INSERT' then
    if new.status <> 'draft' then
      raise exception '政策版本一律從 draft 開始，發布是另一個動作';
    end if;
    return new;
  end if;
  -- 已發布的正文不可悄悄改寫：使用者接受的是他當時看到的那份
  if old.status = 'published' and new.body_text is distinct from old.body_text then
    raise exception '已發布的政策內容不可修改，請建立新版本';
  end if;
  if new.status = 'published' and old.status = 'draft' then
    if new.body_text is null or char_length(btrim(new.body_text)) = 0 then
      raise exception '政策正文是空的，不可發布';
    end if;
    new.published_at := coalesce(old.published_at, now());
  end if;
  if old.status = 'retired' and new.status <> 'retired' then
    raise exception '已停用的版本不可復原，請建立新版本';
  end if;
  return new;
end $$;
drop trigger if exists trg_care_policy_guard on care_policy_versions;
create trigger trg_care_policy_guard before insert or update on care_policy_versions
